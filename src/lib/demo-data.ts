export type SeedResult = { memories: number; embedded: boolean };

/**
 * Inserts the demo user into a project environment. Idempotent: re-running
 * replaces the demo user's data and leaves every other end-user untouched.
 */
export async function seedDemoUser(scope: {
  projectId: string;
  environmentId: string;
}): Promise<SeedResult> {
  const scoped = and(
    eq(memories.projectId, scope.projectId),
    eq(memories.environmentId, scope.environmentId),
    eq(memories.endUserId, DEMO_USER_ID)
  );
  await db.delete(memories).where(scoped);
  await db
    .delete(userProfiles)
    .where(
      and(
        eq(userProfiles.projectId, scope.projectId),
        eq(userProfiles.environmentId, scope.environmentId),
        eq(userProfiles.endUserId, DEMO_USER_ID)
      )
    );

  // One request for every memory rather than one per memory — Voyage's free
  // tier allows three requests a minute, so a loop here would take a quarter of
  // an hour and a batch takes a second.
  let embeddings: number[][] | null = null;
  try {
    embeddings = await embedDocuments(SEEDS.map((seed) => seed.content));
  } catch {
    // Seeding without embeddings still gives a populated Explorer and working
    // keyword recall; the alternative is a signup that fails because a third
    // party is rate-limiting us.
    embeddings = null;
  }

  const now = Date.now();
  const at = (daysAgo: number) => new Date(now - daysAgo * 24 * 60 * 60 * 1000);

  const inserted = await db
    .insert(memories)
    .values(
      SEEDS.map((seed, index) => ({
        projectId: scope.projectId,
        environmentId: scope.environmentId,
        endUserId: DEMO_USER_ID,
        content: seed.content,
        type: seed.type,
        confidence: seed.confidence,
        importance: seed.importance,
        status: seed.status ?? "active",
        sourceType: "demo",
        embedding: embeddings?.[index] ?? null,
        metadata: seed.trivial ? { discarded: "trivial" } : null,
        createdAt: at(seed.daysAgo),
        updatedAt: at(seed.daysAgo),
        lastConfirmedAt: at(seed.daysAgo),
        // Already judged: a demo should not show every memory as awaiting
        // reconciliation, which is a transient state, not the resting one.
        reconciledAt: at(seed.daysAgo),
        recallCount: seed.recallCount ?? 0,
        lastRecalledAt: seed.recallCount ? at(Math.max(1, Math.floor(seed.daysAgo / 3))) : null,
      }))
    )
    .returning({ id: memories.id, content: memories.content });

  const idFor = (key: string) => {
    const index = SEEDS.findIndex((seed) => seed.key === key);
    return index === -1 ? null : inserted[index].id;
  };

  // The version chain: the replacement points at what it replaced.
  for (const [index, seed] of SEEDS.entries()) {
    if (!seed.supersedes) continue;
    const previous = idFor(seed.supersedes);
    if (previous) {
      await db
        .update(memories)
        .set({ supersedesId: previous })
        .where(eq(memories.id, inserted[index].id));
    }
  }

  await db.insert(memoryEvidence).values(
    SEEDS.map((seed, index) => ({
      memoryId: inserted[index].id,
      sourceType: "demo",
      excerpt: seed.excerpt,
      eventType: seed.supersedes ? ("updated" as const) : ("extracted" as const),
      reasoning: seed.supersedeReason ?? null,
      createdAt: at(seed.daysAgo),
    }))
  );

  for (const [index, seed] of SEEDS.entries()) {
    if (!seed.contradicts) continue;
    const other = idFor(seed.contradicts);
    if (!other) continue;
    await db.insert(contradictions).values({
      projectId: scope.projectId,
      memoryIdA: other,
      memoryIdB: inserted[index].id,
      reasoning: seed.contradictionReason ?? "Conflicting statements about the same subject.",
      detectedAt: at(seed.daysAgo),
    });
  }

  const activeIds = inserted
    .filter((_, index) => (SEEDS[index].status ?? "active") === "active")
    .map((row) => row.id);

  await db.insert(userProfiles).values({
    projectId: scope.projectId,
    environmentId: scope.environmentId,
    endUserId: DEMO_USER_ID,
    content: PROFILE,
    sourceMemoryIds: activeIds,
    memoryCount: activeIds.length,
    generatedAt: at(3),
  });

  return { memories: inserted.length, embedded: embeddings !== null };
}
