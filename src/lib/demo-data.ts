/**
 * A demo end-user with a history.
 *
 * Memora is invisible on its first day. Its whole claim is about what happens
 * to knowledge over months — facts superseding other facts, contradictions
 * surfacing, a person becoming legible — and a brand-new project has none of
 * that, so the Playground answers every question with "no memories matched".
 * That is the correct answer and a terrible first impression.
 *
 * So a new project starts with someone already in it. This is not a stub or
 * lorem ipsum: it is a deliberately constructed case where the interesting
 * behaviours are visible in the first thirty seconds —
 *
 *   - a fact that replaced an earlier fact, with the old one still readable
 *     and the reason recorded
 *   - two memories that cannot both be true, left flagged rather than guessed
 *   - a memory extraction kept but marked trivial, still retrievable
 *   - evidence: the sentence each memory was actually learned from
 *   - a profile written from the memories rather than from a template
 *
 * Written by hand rather than generated by running the real pipeline. A demo
 * should tell the same story every time, and 40 extraction calls per signup is
 * a strange thing to pay for.
 */

